-- @about
--   # List of Instruments and Effects
--
--   Lists all REAPER plugins used in an active project, grouping them into
--   categories. The motivation comes from the KVR One Synth Challenge
--   competition, which requires providing technical details of the production.
--
--   Every FX chain REAPER offers is counted: track FX, each track's record
--   input FX, the master track, the monitoring chain, and the FX on media
--   items' takes -- including instruments on takes, which is how a MIDI item
--   makes sound without an instrument on its track. Plugins on a take that is
--   not the one playing back are reported as inactive, as are bypassed and
--   offline ones.
--
--   FX containers are followed, however deep they nest. What a container holds
--   is counted; the container itself is not, being a wrapper rather than a
--   plugin anyone installed. Bypassing a container, or taking it offline,
--   marks everything inside it inactive. An offline container's contents are
--   read out of the project state, since REAPER unloads them and will not
--   report them any other way.
--
--   Results appear in the window immediately, with buttons to copy them to the
--   clipboard in several formats:
--
--   - **plain text** -- the text shown in the preview window
--   - **markdown** -- results formatted into tables
--   - **BB plain** -- some BBCode formatting, such as bold
--   - **BB code** -- wrapped in `[CODE]` tags to force a fixed-width font
--
--   The report is built when the window opens, and rebuilt whenever you press a
--   Copy button or toggle `debug`. Each rebuild reads the project you are
--   looking at now, so it picks up a switch to another project tab. Normally
--   the window shows plain text whichever export format you copy; tick `debug`
--   to make it show exactly what goes to the clipboard.
--
--   The ⓘ button shows the version, the licence and a link to the
--   documentation.
--
--   Requires **ReaImGui 0.10 or newer**, available on ReaPack. Nothing else --
--   neither Lokasenna's GUI library nor SWS is needed any more.
--
--   Written and tested in REAPER 7.x; it may work in earlier versions. GPL v3.
-- @changelog
--   The window is rewritten on ReaImGui. The old one was drawn with Lokasenna's
--   GUI library v2, which knows nothing about display scaling and so came out
--   blurry and undersized on a HiDPI screen; the new one is sharp at any
--   resolution and can be resized. Install **ReaImGui** from ReaPack before
--   updating. Lokasenna's GUI library is no longer required, and neither is
--   SWS -- the clipboard now goes through ReaImGui.
--
--   Plugins on media items are counted. REAPER lets a take carry its own FX
--   chain, instruments included, and none of it was reported before: a project
--   driven by a take instrument listed no instrument at all. FX on the active
--   take are counted as instruments or effects like any others, and FX on the
--   other takes are listed under offline/inactive, since they do not play.
--
--   Record input FX are counted, in a new **Input FX** section. Only the master
--   track's input chain -- the monitoring chain -- was read before, so input FX
--   on ordinary tracks were invisible.
--
--   FX inside containers are counted. REAPER 7 lets an FX be a container
--   holding a chain of its own, and everything in one was invisible: the report
--   named the container and nothing it held. Containers are now followed to any
--   depth, the container itself is no longer listed as though it were a plugin,
--   and bypassing or offlining one marks its whole contents inactive. An
--   OFFLINE container needs special handling: REAPER unloads it and then
--   answers nothing about it, so its contents are read out of the project
--   state instead. Reading inside containers needs REAPER 7.06 or newer.
--
--   The Markdown tables line up. The `Plugin Name` heading was left out
--   of the column width, so a section whose longest name was shorter than the
--   heading drew a heading overhanging its own column; and the padding counted
--   bytes rather than characters, so any name with an accent came out short.
--
--   The window has an ⓘ button: the version you are running, the author, the
--   licence, and links to the documentation and the source. The window behind
--   dims while the dialog is open. Close it with its Close button, with Escape,
--   or by clicking outside it.
--
--   The report follows the project you are actually looking at. Before, the
--   track list was read from whichever project was open when the script
--   started, while the master and monitoring chains followed the current one,
--   so after switching project tab the two halves of the report described
--   different projects.

